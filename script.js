const THEME_KEY = "theme";
const LANG_KEY = "lang";
const LANG_ATTR = { pt: "pt", en: "en", es: "es" };

function t(lang, key) {
  const table = translations[lang] || translations.pt;
  return table[key] ?? translations.pt[key] ?? key;
}

function applyTheme(theme) {
  const isDark = theme === "dark";
  document.documentElement.classList.toggle("dark", isDark);
  localStorage.setItem(THEME_KEY, isDark ? "dark" : "light");
}

function toggleTheme() {
  const next = document.documentElement.classList.contains("dark")
    ? "light"
    : "dark";
  applyTheme(next);
}

function applyLanguage(lang) {
  const next = translations[lang] ? lang : "pt";
  document.documentElement.lang = LANG_ATTR[next];
  localStorage.setItem(LANG_KEY, next);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = t(next, el.getAttribute("data-i18n"));
    if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
      el.placeholder = value;
      return;
    }
    if (el instanceof HTMLMetaElement) {
      el.setAttribute("content", value);
      return;
    }
    el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(next, el.getAttribute("data-i18n-aria")));
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === next;
    btn.classList.toggle("text-cyan-600", active);
    btn.classList.toggle("dark:text-cyan-400", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  const feedback = document.getElementById("form-feedback");
  if (feedback && !feedback.classList.contains("hidden")) {
    feedback.textContent = t(next, "contact.feedback");
  }
}

function currentLang() {
  return localStorage.getItem(LANG_KEY) || "pt";
}

document.addEventListener("DOMContentLoaded", () => {
  applyTheme(localStorage.getItem(THEME_KEY) || "dark");
  applyLanguage(currentLang());

  document.getElementById("theme-toggle").addEventListener("click", toggleTheme);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.getAttribute("data-lang"));
    });
  });

  document.querySelectorAll(".nav-link").forEach((link) => {
    link.addEventListener("click", (event) => {
      const href = link.getAttribute("href");
      if (!href || !href.startsWith("#")) {
        return;
      }

      const target = document.querySelector(href);
      if (!target) {
        return;
      }

      event.preventDefault();
      target.scrollIntoView({ behavior: "smooth", block: "start" });
      history.replaceState(null, "", href);
    });
  });

  const form = document.getElementById("contact-form");
  const feedback = document.getElementById("form-feedback");

  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();

      if (!form.checkValidity()) {
        form.reportValidity();
        return;
      }

      if (feedback) {
        feedback.textContent = t(currentLang(), "contact.feedback");
        feedback.classList.remove("hidden");
      }
      form.reset();
      applyLanguage(currentLang());
    });
  }
});
